//! The generated TypeScript client for the client surface: one function per
//! route in the manifest, typed with the ts-rs projections of the same
//! request and response types, over one shared request helper that raises
//! the wire error contract. Rendered by the projection test into
//! `frontend/src/lib/protocol/client.ts` beside the type bindings, so a
//! route change is a stale-projection failure at the gate until the client
//! regenerates.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use super::routes::{Method, Route, routes};

/// Render the client module. Deterministic: same manifest, same text.
pub fn render() -> String {
    let routes = routes();
    let mut imports = BTreeSet::new();
    for route in &routes {
        imports.extend(route.request.iter().map(|name| name.to_string()));
        imports.extend(route.response.body.iter().map(|name| name.to_string()));
    }
    let mut out = String::new();
    out.push_str(
        "// Generated by swage-protocol's projection test from the client route\n\
         // manifest (crates/swage-protocol/src/client/routes.rs). Do not edit:\n\
         // change the manifest and regenerate.\n\n",
    );
    for name in &imports {
        let _ = writeln!(out, "import type {{ {name} }} from \"./{name}\";");
    }
    out.push_str("import { ApiError } from \"../api/error\";\n\n");
    out.push_str(
        "let baseUrl = \"\";\n\n\
         /** Prefix every request with a base URL (empty means same-origin). */\n\
         export function setClientBaseUrl(url: string): void {\n\
         \x20 baseUrl = url;\n\
         }\n\n\
         async function request<T>(\n\
         \x20 method: string,\n\
         \x20 path: string,\n\
         \x20 body?: unknown,\n\
         ): Promise<T> {\n\
         \x20 const init: RequestInit = { method };\n\
         \x20 if (body !== undefined) {\n\
         \x20   init.headers = { \"Content-Type\": \"application/json\" };\n\
         \x20   init.body = JSON.stringify(body);\n\
         \x20 }\n\
         \x20 const response = await fetch(`${baseUrl}${path}`, init);\n\
         \x20 if (!response.ok) {\n\
         \x20   throw await ApiError.fromResponse(response, method, path);\n\
         \x20 }\n\
         \x20 if (response.status === 204) {\n\
         \x20   return undefined as T;\n\
         \x20 }\n\
         \x20 return (await response.json()) as T;\n\
         }\n",
    );
    for route in &routes {
        out.push('\n');
        render_function(&mut out, route);
    }
    out
}

fn render_function(out: &mut String, route: &Route) {
    let mut signature: Vec<String> = route
        .path_parameters
        .iter()
        .map(|parameter| format!("{}: string", camel(parameter.name)))
        .collect();
    if let Some(request) = route.request.as_ref() {
        let optional = if route.request_optional { "?" } else { "" };
        signature.push(format!("body{optional}: {request}"));
    }
    signature.extend(route.query_parameters.iter().map(|parameter| {
        let optional = if parameter.required { "" } else { "?" };
        format!("{}{}: string", camel(parameter.name), optional)
    }));
    let return_type = route
        .response
        .body
        .as_ref()
        .map_or_else(|| "void".to_string(), |body| body.to_string());
    let mut path = route.path.to_string();
    for parameter in &route.path_parameters {
        path = path.replace(
            &format!("{{{}}}", parameter.name),
            &format!("${{encodeURIComponent({})}}", camel(parameter.name)),
        );
    }
    let method = match route.method {
        Method::Get => "GET",
        Method::Post => "POST",
        Method::Put => "PUT",
        Method::Delete => "DELETE",
    };
    let body_argument = if route.request.is_some() {
        ", body"
    } else {
        ""
    };
    let _ = writeln!(out, "/** {} */", route.summary);
    let _ = writeln!(
        out,
        "export async function {}({}): Promise<{return_type}> {{",
        camel(route.operation_id),
        signature.join(", ")
    );
    if route.query_parameters.is_empty() {
        let _ = writeln!(
            out,
            "  return request<{return_type}>(\"{method}\", `{path}`{body_argument});"
        );
    } else {
        out.push_str("  const query = new URLSearchParams();\n");
        for parameter in &route.query_parameters {
            let name = camel(parameter.name);
            if parameter.required {
                let _ = writeln!(out, "  query.set(\"{}\", {name});", parameter.name);
            } else {
                let _ = writeln!(out, "  if ({name} !== undefined) query.set(\"{}\", {name});", parameter.name);
            }
        }
        let _ = writeln!(
            out,
            "  const suffix = query.size === 0 ? \"\" : `?${{query}}`;\n  return request<{return_type}>(\"{method}\", `{path}${{suffix}}`{body_argument});"
        );
    }
    out.push_str("}\n");
}

/// `snake_case` to `camelCase`, the client's naming.
fn camel(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut upper_next = false;
    for character in name.chars() {
        if character == '_' {
            upper_next = true;
        } else if upper_next {
            out.extend(character.to_uppercase());
            upper_next = false;
        } else {
            out.push(character);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_route_renders_one_typed_function() {
        let rendered = render();
        assert!(rendered.contains(
            "export async function listSpaces(): Promise<SpaceListResponse> {\n  return request<SpaceListResponse>(\"GET\", `/api/spaces`);\n}"
        ));
        assert!(rendered.contains(
            "export async function createSpace(body: CreateSpaceRequest): Promise<SpaceResponse> {\n  return request<SpaceResponse>(\"POST\", `/api/spaces`, body);\n}"
        ));
        assert!(rendered.contains(
            "export async function getSpace(id: string): Promise<SpaceResponse> {\n  return request<SpaceResponse>(\"GET\", `/api/spaces/${encodeURIComponent(id)}`);\n}"
        ));
        assert!(rendered.contains(
            "export async function deleteSpace(id: string): Promise<void> {\n  return request<void>(\"DELETE\", `/api/spaces/${encodeURIComponent(id)}`);\n}"
        ));
    }

    #[test]
    fn imports_cover_exactly_the_named_types_once() {
        let rendered = render();
        assert_eq!(
            rendered
                .matches("import type { SpaceResponse } from \"./SpaceResponse\";")
                .count(),
            1
        );
        assert!(
            rendered.contains("import type { CreateSpaceRequest } from \"./CreateSpaceRequest\";")
        );
        assert!(rendered.contains("import { ApiError } from \"../api/error\";"));
    }

    #[test]
    fn rendering_is_deterministic() {
        assert_eq!(render(), render());
    }

    #[test]
    fn names_become_camel_case() {
        assert_eq!(camel("list_spaces"), "listSpaces");
        assert_eq!(camel("id"), "id");
        assert_eq!(camel("workspace_id"), "workspaceId");
    }

    #[test]
    fn optional_queries_and_string_paths_render_into_the_client_function() {
        let rendered = render();
        assert!(rendered.contains(
            "export async function discoverProviderModels(id: string, q?: string): Promise<ModelDiscoveryResponse>"
        ));
        assert!(rendered.contains(
            "export async function discoverDraftProviderModels(id: string, body: SaveProviderSettings, q?: string): Promise<ModelDiscoveryResponse>"
        ));
        assert!(rendered.contains(
            "if (q !== undefined) query.set(\"q\", q);\n  const suffix = query.size === 0 ? \"\" : `?${query}`;\n  return request<ModelDiscoveryResponse>(\"GET\", `/api/settings/providers/${encodeURIComponent(id)}/models${suffix}`);"
        ));
    }
}

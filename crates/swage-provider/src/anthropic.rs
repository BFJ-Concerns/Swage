#[async_trait]
impl LlmProvider for AnthropicProvider {
    fn model_id(&self) -> &str {
        &self.config.model
    }

    fn provider_request_snapshot(
        &self,
        request: &CompletionRequest,
        stream: bool,
    ) -> serde_json::Value {
        serde_json::json!({
            "provider": "anthropic",
            "protocol": "messages",
            "stream": stream,
            "body": self.build_request_for_completion(request, stream),
        })
    }

    async fn complete(
        &self,
        request: CompletionRequest,
    ) -> Result<CompletionResponse, ProviderError> {
        let body = self.build_request_for_completion(&request, false);
        let client = self.make_http_client();
        let response: MessagesResponse = client.post_json("/v1/messages", &body).await?;

        // Collect all text blocks; ignore tool_use blocks (none expected here).
        let content = response
            .content
            .into_iter()
            .filter_map(|b| match b {
                ContentBlock::Text { text } => Some(text),
                _ => None,
            })
            .collect::<Vec<_>>()
            .join("");

        Ok(CompletionResponse {
            content,
            input_tokens: response.usage.input_tokens,
            output_tokens: response.usage.output_tokens,
            finish_reason: map_stop_reason(response.stop_reason.as_deref()),
            cost: None,
        })
    }

    async fn complete_with_tools(
        &self,
        request: ToolCompletionRequest,
    ) -> Result<ToolCompletionResponse, ProviderError> {
        let body = self.build_request_for_tool_completion(&request, false);
        let client = self.make_http_client();
        let response: MessagesResponse = client.post_json("/v1/messages", &body).await?;

        let mut content = String::new();
        let mut tool_calls = Vec::new();

        // Responses may interleave text and tool_use blocks — collect both.
        for block in response.content {
            match block {
                ContentBlock::Text { text } => content.push_str(&text),
                ContentBlock::ToolUse { id, name, input } => {
                    tool_calls.push(ToolCall {
                        call_id: id,
                        name,
                        arguments: input,
                    });
                }
            }
        }

        Ok(ToolCompletionResponse {
            content,
            input_tokens: response.usage.input_tokens,
            output_tokens: response.usage.output_tokens,
            finish_reason: map_stop_reason(response.stop_reason.as_deref()),
            cost: None,
            tool_calls,
        })
    }

    fn stream(
        &self,
        request: CompletionRequest,
    ) -> Pin<Box<dyn Stream<Item = StreamChunk> + Send>> {
        // stream() is synchronous, so we spawn a task that drives the async
        // SSE stream and forwards chunks to the caller via a channel — the
        // same pattern used by the legacy stream_message().
        let body = self.build_request_for_completion(&request, true);
        let client = self.make_http_client();

        spawn_stream_forwarder(move |tx| async move {
            let (metadata, sse_stream) = match client
                .post_stream("/v1/messages", &body, HeaderMap::new())
                .await
            {
                Ok(s) => s,
                Err(e) => {
                    let _ = tx.send(StreamChunk::Error {
                        message: e.to_string(),
                    });
                    return;
                }
            };

            forward_anthropic_stream(metadata, sse_stream, tx).await;
        })
    }
}


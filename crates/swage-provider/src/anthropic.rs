/// Map Anthropic's `stop_reason` string to a `FinishReason` variant.
///
/// Anthropic returns `"end_turn"` for natural completion and `"tool_use"` when
/// the model issued tool calls. Any unrecognised value maps to `Unknown`.
fn map_stop_reason(stop_reason: Option<&str>) -> FinishReason {
    match stop_reason {
        Some("end_turn") => FinishReason::Stop,
        Some("tool_use") => FinishReason::ToolUse,
        Some("max_tokens") => FinishReason::Length,
        _ => FinishReason::Unknown,
    }
}

impl AnthropicProvider {
    /// Convert a slice of `ChatMessage` values to Anthropic wire messages.
    ///
    /// System-role messages are extracted and concatenated into a single
    /// system string (returned as `Option<String>`). Remaining messages
    /// become `AnthropicMessage` entries in order.
    fn to_anthropic_messages(messages: &[ChatMessage]) -> (Option<String>, Vec<AnthropicMessage>) {
        let system_parts: Vec<String> = messages
            .iter()
            .filter(|m| m.role() == Role::System)
            .flat_map(|m| {
                m.content().iter().filter_map(|p| {
                    if let ContentPart::Text { text } = p {
                        Some(text.clone())
                    } else {
                        None
                    }
                })
            })
            .collect();
        let system = if system_parts.is_empty() {
            None
        } else {
            Some(system_parts.join("\n"))
        };

        let wire_messages = messages
            .iter()
            .filter(|m| m.role() != Role::System)
            .map(|m| {
                let content = Self::message_content_for_anthropic(m);
                AnthropicMessage {
                    role: m.role().to_string(),
                    content,
                }
            })
            .collect();

        (system, wire_messages)
    }

    fn message_content_for_anthropic(message: &ChatMessage) -> MessageContent {
        if let Some(replay) = message.tool_replay() {
            return MessageContent::Blocks(Self::tool_replay_to_anthropic_blocks(replay));
        }

        let text = message
            .content()
            .iter()
            .filter_map(|p| {
                if let ContentPart::Text { text } = p {
                    Some(text.as_str())
                } else {
                    None
                }
            })
            .collect::<Vec<_>>()
            .join("");
        MessageContent::Text(text)
    }

    fn tool_replay_to_anthropic_blocks(replay: &[ToolReplayPart]) -> Vec<serde_json::Value> {
        replay
            .iter()
            .map(|part| match part {
                ToolReplayPart::Text { text } => serde_json::json!({
                    "type": "text",
                    "text": text,
                }),
                ToolReplayPart::Reasoning { content, .. } => serde_json::json!({
                    "type": "text",
                    "text": content,
                }),
                ToolReplayPart::ToolCall {
                    call_id,
                    name,
                    arguments,
                } => serde_json::json!({
                    "type": "tool_use",
                    "id": call_id,
                    "name": name,
                    "input": arguments,
                }),
                ToolReplayPart::ToolResult {
                    call_id,
                    content,
                    is_error,
                } => {
                    let mut block = serde_json::json!({
                        "type": "tool_result",
                        "tool_use_id": call_id,
                        "content": content,
                    });
                    if *is_error {
                        block["is_error"] = serde_json::Value::Bool(true);
                    }
                    block
                }
            })
            .collect()
    }

    /// Build a `MessagesRequest` from a `CompletionRequest`.
    ///
    /// System messages are extracted to the top-level `system` field.
    /// The model from the request overrides the provider's configured model
    /// when present.
    fn build_request_for_completion(
        &self,
        request: &CompletionRequest,
        stream: bool,
    ) -> MessagesRequest {
        let (system, messages) = Self::to_anthropic_messages(&request.messages);
        MessagesRequest {
            model: request
                .model
                .clone()
                .unwrap_or_else(|| self.config.model.clone()),
            messages,
            max_tokens: request.max_tokens.unwrap_or(4096),
            system,
            stream: if stream { Some(true) } else { None },
            tools: request
                .tool_definitions
                .iter()
                .filter_map(|def| {
                    let name = def["name"].as_str()?.to_owned();
                    let description = def["description"].as_str().unwrap_or("").to_owned();
                    let input_schema = def
                        .get("input_schema")
                        .or_else(|| def.get("parameters"))
                        .map(crate::tool_schema::provider_tool_schema)
                        .unwrap_or_else(|| serde_json::json!({"type": "object", "properties": {}}));
                    Some(AnthropicTool {
                        name,
                        description,
                        input_schema,
                    })
                })
                .collect(),
        }
    }

    /// Build a `MessagesRequest` from a `ToolCompletionRequest`.
    ///
    /// Tool definitions are converted from the generic JSON schema format to
    /// Anthropic wire format. Both `input_schema` (Anthropic-native) and
    /// `parameters` (OpenAI-style) are accepted as the schema source.
    fn build_request_for_tool_completion(
        &self,
        request: &ToolCompletionRequest,
        stream: bool,
    ) -> MessagesRequest {
        let (system, messages) = Self::to_anthropic_messages(&request.messages);

        let tools = request
            .tool_definitions
            .iter()
            .filter_map(|def| {
                let name = def["name"].as_str()?.to_owned();
                let description = def["description"].as_str().unwrap_or("").to_owned();
                // Anthropic requires `input_schema`; accept `parameters` as a fallback
                // to support OpenAI-style tool definitions without conversion.
                let input_schema = def
                    .get("input_schema")
                    .or_else(|| def.get("parameters"))
                    .map(crate::tool_schema::provider_tool_schema)
                    .unwrap_or_else(|| serde_json::json!({"type": "object", "properties": {}}));
                Some(AnthropicTool {
                    name,
                    description,
                    input_schema,
                })
            })
            .collect();

        MessagesRequest {
            model: request
                .model
                .clone()
                .unwrap_or_else(|| self.config.model.clone()),
            messages,
            max_tokens: request.max_tokens.unwrap_or(4096),
            system,
            stream: if stream { Some(true) } else { None },
            tools,
        }
    }
}


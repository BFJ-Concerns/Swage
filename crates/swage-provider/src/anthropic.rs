// The old send_message/stream_message implementations are preserved below as
// private methods. Task [8uce] will adapt them to the new four-method API.

impl AnthropicProvider {
    /// Legacy send_message logic — kept for task [8uce] to adapt into `complete`.
    #[allow(dead_code)]
    async fn legacy_send_message(
        &self,
        request: &LlmRequest,
    ) -> Result<LlmResponse, ProviderError> {
        let body = self.build_messages_request(request, false);
        let client = self.make_http_client();

        let response: MessagesResponse = client.post_json("/v1/messages", &body).await?;

        let text = response
            .content
            .into_iter()
            .filter_map(|b| match b {
                ContentBlock::Text { text } => Some(text),
                _ => None,
            })
            .collect::<Vec<_>>()
            .join("");

        Ok(LlmResponse {
            message: ChatMessage::new(Role::Assistant, text),
            usage: TokenUsage {
                input_tokens: response.usage.input_tokens,
                output_tokens: response.usage.output_tokens,
            },
            model: response.model,
        })
    }

    /// Legacy stream_message logic — kept for task [8uce] to adapt into `stream`.
    #[allow(dead_code)]
    fn legacy_stream_message(
        &self,
        request: &LlmRequest,
    ) -> Pin<Box<dyn Stream<Item = StreamChunk> + Send>> {
        let body = self.build_messages_request(request, true);
        let client = self.make_http_client();

        spawn_stream_forwarder(move |tx| async move {
            let (metadata, sse_stream) = match client
                .post_stream("/v1/messages", &body, HeaderMap::new())
                .await
            {
                Ok(s) => s,
                Err(e) => {
                    let _ = tx.send(StreamChunk::Error {
                        message: e.to_string(),
                    });
                    return;
                }
            };

            forward_anthropic_stream(metadata, sse_stream, tx).await;
        })
    }
}


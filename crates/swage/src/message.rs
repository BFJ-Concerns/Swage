//! Shared message types for conversations.
//!
//! Contains the fundamental types for representing conversation history
//! across both LLM provider interactions and storage persistence.

use serde::{Deserialize, Serialize};

/// A message in a conversation.
///
/// Messages form the dialogue history sent to the LLM. The model uses this context
/// to generate the next response.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Message {
    /// The role of the message author.
    pub role: Role,

    /// The message content.
    pub content: String,
}

/// The role of a message author in a conversation.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// System instructions that guide the model's behaviour.
    System,

    /// Messages from the user.
    User,

    /// Messages generated by the assistant (model).
    Assistant,
}
